  localAnswer(text) {
    const t = text.toLowerCase().replace(/\s+/g, "");
    for (const item of this.faq) {
      if (item.keys.some(k => t.includes(k.toLowerCase().replace(/\s+/g, "")))) return item.answer;
    }
    return this.fallback;
  },

  _remember(q, a) {
    this.history.push({ role: "user", content: q }, { role: "assistant", content: a });
    if (this.history.length > 10) this.history = this.history.slice(-10);
  },

  async ask(text) {
    if (this.API_URL) {
      try {
        const res = await fetch(this.API_URL, {
          method: "POST",
          headers: { "Content-Type": "application/json" },
          body: JSON.stringify({ message: text, history: this.history })
        });
        if (res.ok) {
          const data = await res.json();
          if (data.answer) { this._remember(text, data.answer); return data.answer; }
        } else {
          console.info("AI 서버 응답 없음(" + res.status + "), 사전 답변으로 대체합니다.");
        }
      } catch (e) {
        console.warn("AI 서버 연결 실패, 사전 답변으로 대체합니다.", e);
      }
    }
    // 잠깐 생각하는 느낌을 주기 위한 짧은 대기
    await new Promise(r => setTimeout(r, 500));
    const a = this.localAnswer(text);
    this._remember(text, a);
    return a;
  }
